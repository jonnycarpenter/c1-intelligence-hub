"""Report Service - Generate exportable reports in various formats."""

import io
import uuid
from datetime import datetime
from typing import List, Optional
from pathlib import Path

from app.api.schemas import ReportExportItem, ExportFormat
from app.utils.logger import get_logger
from app.config.settings import settings

logger = get_logger(__name__)


class ReportService:
    """
    Service for generating exportable reports.
    
    Supports:
    - PDF: Professional document format
    - DOCX: Microsoft Word format for editing
    - PPTX: PowerPoint for presentations
    """
    
    def __init__(self):
        """Initialize the report service."""
        self._export_dir = Path(settings.base_dir) / "exports"
        self._export_dir.mkdir(exist_ok=True)
    
    async def export_report(
        self,
        format: ExportFormat,
        items: List[ReportExportItem],
        title: str = "Intelligence Report",
    ) -> bytes:
        """
        Export report items to the specified format.
        
        Args:
            format: Output format (pdf, docx, pptx)
            items: List of report items to include
            title: Report title
            
        Returns:
            Binary content of the generated file
        """
        logger.info(f"Exporting report: format={format.value}, items={len(items)}, title={title}")
        
        if format == ExportFormat.PDF:
            return await self._export_pdf(items, title)
        elif format == ExportFormat.DOCX:
            return await self._export_docx(items, title)
        elif format == ExportFormat.PPTX:
            return await self._export_pptx(items, title)
        else:
            raise ValueError(f"Unsupported format: {format}")
    
    async def _export_pdf(
        self,
        items: List[ReportExportItem],
        title: str,
    ) -> bytes:
        """
        Generate PDF report.
        
        Uses reportlab for PDF generation.
        """
        try:
            from reportlab.lib import colors
            from reportlab.lib.pagesizes import letter
            from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
            from reportlab.lib.units import inch
            from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
        except ImportError:
            logger.warning("reportlab not installed, generating placeholder PDF")
            return self._generate_placeholder_content("pdf", items, title)
        
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=letter)
        styles = getSampleStyleSheet()
        
        # Custom styles
        title_style = ParagraphStyle(
            'CustomTitle',
            parent=styles['Heading1'],
            fontSize=24,
            spaceAfter=30,
            textColor=colors.HexColor('#1a1a2e'),
        )
        
        heading_style = ParagraphStyle(
            'CustomHeading',
            parent=styles['Heading2'],
            fontSize=14,
            spaceBefore=20,
            spaceAfter=10,
            textColor=colors.HexColor('#16213e'),
        )
        
        body_style = ParagraphStyle(
            'CustomBody',
            parent=styles['Normal'],
            fontSize=11,
            spaceAfter=12,
            leading=16,
        )
        
        source_style = ParagraphStyle(
            'Source',
            parent=styles['Normal'],
            fontSize=9,
            textColor=colors.HexColor('#666666'),
            spaceBefore=5,
        )
        
        elements = []
        
        # Title
        elements.append(Paragraph(title, title_style))
        elements.append(Paragraph(
            f"Generated: {datetime.now().strftime('%B %d, %Y at %I:%M %p')}",
            source_style
        ))
        elements.append(Spacer(1, 20))
        
        # Content items
        for i, item in enumerate(items, 1):
            # Item title if available
            if item.title:
                elements.append(Paragraph(f"{i}. {item.title}", heading_style))
            else:
                elements.append(Paragraph(f"Item {i}", heading_style))
            
            # Content
            # Clean content for PDF (escape special characters)
            content = item.content.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            elements.append(Paragraph(content, body_style))
            
            # Source
            elements.append(Paragraph(f"Source: {item.source}", source_style))
            elements.append(Spacer(1, 15))
        
        # Footer
        elements.append(Spacer(1, 30))
        elements.append(Paragraph(
            "Generated by C1 Intelligence Hub",
            source_style
        ))
        
        doc.build(elements)
        buffer.seek(0)
        return buffer.getvalue()
    
    async def _export_docx(
        self,
        items: List[ReportExportItem],
        title: str,
    ) -> bytes:
        """
        Generate Word document.
        
        Uses python-docx for DOCX generation.
        """
        try:
            from docx import Document
            from docx.shared import Inches, Pt
            from docx.enum.text import WD_ALIGN_PARAGRAPH
        except ImportError:
            logger.warning("python-docx not installed, generating placeholder")
            return self._generate_placeholder_content("docx", items, title)
        
        doc = Document()
        
        # Title
        title_para = doc.add_heading(title, 0)
        title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        
        # Subtitle with date
        subtitle = doc.add_paragraph()
        subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = subtitle.add_run(f"Generated: {datetime.now().strftime('%B %d, %Y at %I:%M %p')}")
        run.font.size = Pt(10)
        run.font.italic = True
        
        doc.add_paragraph()  # Spacer
        
        # Content items
        for i, item in enumerate(items, 1):
            # Item heading
            if item.title:
                doc.add_heading(f"{i}. {item.title}", level=2)
            else:
                doc.add_heading(f"Item {i}", level=2)
            
            # Content
            doc.add_paragraph(item.content)
            
            # Source
            source_para = doc.add_paragraph()
            source_run = source_para.add_run(f"Source: {item.source}")
            source_run.font.size = Pt(9)
            source_run.font.italic = True
            
            doc.add_paragraph()  # Spacer
        
        # Footer
        doc.add_paragraph()
        footer = doc.add_paragraph()
        footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = footer.add_run("Generated by C1 Intelligence Hub")
        run.font.size = Pt(9)
        run.font.italic = True
        
        buffer = io.BytesIO()
        doc.save(buffer)
        buffer.seek(0)
        return buffer.getvalue()
    
    async def _export_pptx(
        self,
        items: List[ReportExportItem],
        title: str,
    ) -> bytes:
        """
        Generate PowerPoint presentation.
        
        Uses python-pptx for PPTX generation.
        """
        try:
            from pptx import Presentation
            from pptx.util import Inches, Pt
            from pptx.dml.color import RgbColor
            from pptx.enum.text import PP_ALIGN
        except ImportError:
            logger.warning("python-pptx not installed, generating placeholder")
            return self._generate_placeholder_content("pptx", items, title)
        
        prs = Presentation()
        prs.slide_width = Inches(13.333)  # Widescreen 16:9
        prs.slide_height = Inches(7.5)
        
        # Title slide
        title_slide_layout = prs.slide_layouts[0]
        slide = prs.slides.add_slide(title_slide_layout)
        
        title_shape = slide.shapes.title
        title_shape.text = title
        
        subtitle = slide.placeholders[1]
        subtitle.text = f"Generated: {datetime.now().strftime('%B %d, %Y')}\nC1 Intelligence Hub"
        
        # Content slides (one per item or grouped)
        content_layout = prs.slide_layouts[1]  # Title and Content layout
        
        for i, item in enumerate(items, 1):
            slide = prs.slides.add_slide(content_layout)
            
            # Title
            title_shape = slide.shapes.title
            if item.title:
                title_shape.text = item.title
            else:
                title_shape.text = f"Intelligence Item {i}"
            
            # Content
            content_shape = slide.placeholders[1]
            tf = content_shape.text_frame
            
            # Main content
            p = tf.paragraphs[0]
            p.text = item.content[:500]  # Truncate for slides
            p.font.size = Pt(18)
            
            if len(item.content) > 500:
                p2 = tf.add_paragraph()
                p2.text = "..."
                p2.font.size = Pt(14)
                p2.font.italic = True
            
            # Source
            p3 = tf.add_paragraph()
            p3.text = f"Source: {item.source}"
            p3.font.size = Pt(12)
            p3.font.italic = True
        
        # Summary slide
        blank_layout = prs.slide_layouts[6]  # Blank
        slide = prs.slides.add_slide(blank_layout)
        
        # Add summary text box
        left = Inches(1)
        top = Inches(2.5)
        width = Inches(11.333)
        height = Inches(2)
        
        txBox = slide.shapes.add_textbox(left, top, width, height)
        tf = txBox.text_frame
        p = tf.paragraphs[0]
        p.text = f"Total Items: {len(items)}"
        p.font.size = Pt(24)
        p.alignment = PP_ALIGN.CENTER
        
        p2 = tf.add_paragraph()
        p2.text = "Thank you for using C1 Intelligence Hub"
        p2.font.size = Pt(18)
        p2.alignment = PP_ALIGN.CENTER
        p2.font.italic = True
        
        buffer = io.BytesIO()
        prs.save(buffer)
        buffer.seek(0)
        return buffer.getvalue()
    
    def _generate_placeholder_content(
        self,
        format: str,
        items: List[ReportExportItem],
        title: str,
    ) -> bytes:
        """
        Generate placeholder content when required libraries are not available.
        
        Returns a simple text-based representation.
        """
        content = f"# {title}\n"
        content += f"Generated: {datetime.now().isoformat()}\n\n"
        
        for i, item in enumerate(items, 1):
            content += f"## {i}. {item.title or 'Item'}\n"
            content += f"{item.content}\n"
            content += f"Source: {item.source}\n\n"
        
        content += "\n---\nGenerated by C1 Intelligence Hub\n"
        content += f"Note: Install required libraries for {format.upper()} export\n"
        
        return content.encode('utf-8')
