#!/usr/bin/env python3
"""
Migration: Add BLUF column to weekly_briefings table
====================================================

The BLUF (Bottom Line Up Front) field was being generated by Agent 2 but never
persisted to BigQuery. This migration adds the column.

Usage:
    cd backend
    python scripts/operations/migrations/add_bluf_column.py

Note: BigQuery ALTER TABLE ADD COLUMN is non-destructive - existing rows will
have NULL for the new column, which our code handles gracefully.
"""

import asyncio
import sys
import os

# Add backend to path
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', '..'))

from google.cloud import bigquery


async def add_bluf_column():
    """Add bluf column to weekly_briefings table."""
    
    # Configuration
    project_id = os.environ.get('GCP_PROJECT_ID', 'gen-lang-client-0436975498')
    dataset_id = os.environ.get('GCP_DATASET_ID', 'c1_intelligence')
    table_id = f"{project_id}.{dataset_id}.weekly_briefings"
    
    print(f"Migration: Adding 'bluf' column to {table_id}")
    print("=" * 60)
    
    client = bigquery.Client(project=project_id)
    
    # Check if column already exists
    try:
        table = client.get_table(table_id)
        existing_columns = [field.name for field in table.schema]
        
        if 'bluf' in existing_columns:
            print("✓ Column 'bluf' already exists. Nothing to do.")
            return True
        
        print(f"Current columns: {existing_columns}")
        print("Adding 'bluf' column...")
        
    except Exception as e:
        print(f"✗ Error getting table: {e}")
        return False
    
    # Add the column using ALTER TABLE
    alter_query = f"""
        ALTER TABLE `{table_id}`
        ADD COLUMN IF NOT EXISTS bluf STRING
    """
    
    try:
        query_job = client.query(alter_query)
        query_job.result()  # Wait for completion
        print("✓ Column 'bluf' added successfully!")
        
        # Verify
        table = client.get_table(table_id)
        new_columns = [field.name for field in table.schema]
        print(f"New columns: {new_columns}")
        
        if 'bluf' in new_columns:
            print("\n✓ Migration complete!")
            return True
        else:
            print("\n✗ Column not found after migration - check manually")
            return False
            
    except Exception as e:
        print(f"✗ Error adding column: {e}")
        return False


if __name__ == "__main__":
    print("\n" + "=" * 60)
    print("MIGRATION: Add BLUF column to weekly_briefings")
    print("=" * 60 + "\n")
    
    success = asyncio.run(add_bluf_column())
    sys.exit(0 if success else 1)
